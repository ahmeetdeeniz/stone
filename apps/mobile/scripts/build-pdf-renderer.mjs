// Generates src/pdf/pdf-renderer-html.ts: the page the PDF renderer WebView loads, with
// pdf.js (pdfjs-dist, Apache-2.0) inlined. The legacy build carries polyfills for the newer
// language features pdf.js uses, which Android System WebView versions may not have yet. Run `pnpm pdf:bundle` after updating pdfjs-dist.
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const pdfjs = dirname(require.resolve("pdfjs-dist/package.json"));
const { version } = JSON.parse(await readFile(join(pdfjs, "package.json"), "utf8"));
const main = await readFile(join(pdfjs, "legacy/build/pdf.min.mjs"), "utf8");
const worker = await readFile(join(pdfjs, "legacy/build/pdf.worker.min.mjs"), "utf8");
const page = await readFile(join(here, "pdf-renderer-page.js"), "utf8");

// A literal "</script" inside the inlined sources would end the script element early.
const literal = (code) => JSON.stringify(code).replaceAll("</", "<\\/");
const html =
  '<!doctype html><html><head><meta charset="utf-8" /></head><body><script type="module">' +
  `const PDFJS_MAIN = ${literal(main)};\nconst PDFJS_WORKER = ${literal(worker)};\n${page}` +
  "</script></body></html>";

await writeFile(
  join(here, "../src/pdf/pdf-renderer-html.ts"),
  `// Generated by apps/mobile/scripts/build-pdf-renderer.mjs from pdfjs-dist ${version} (Apache-2.0).\n` +
    `export const PDF_RENDERER_HTML = ${JSON.stringify(html)};\n`,
  "utf8",
);
